#!/usr/bin/env python3
"""docs/failure-gallery.md from the pilot and load-test data: what went wrong,
why, and whether it was fixed. Written by a script so the examples stay the
ones the harness actually produced.

    python research/harness/failure_gallery.py
"""
from __future__ import annotations
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "failure-gallery.md"


def load(name):
    p = ROOT / "research" / name
    return json.loads(p.read_text()) if p.exists() else None


def main() -> int:
    v0, v1, lt = load("real_asr_v0.json"), load("real_asr.json"), load("load_test.json")
    lines = ["# Failure gallery", "",
             "Real cases the harnesses produced, with the cause and what was done. Generated by",
             "`research/harness/failure_gallery.py` from `research/real_asr_v0.json` (bridge before the",
             "guards), `research/real_asr.json` (after) and `research/load_test.json`. A project that only",
             "shows its wins is hiding its evaluation.", ""]
    if v0:
        lines += ["## 1. Harmful corrections on a real recogniser (before the guards)", "",
                  f"Pilot: {v0.get('label', '')}. The bridge made {v0['overall']['corrections']['harmful']} harmful corrections "
                  f"in {v0['overall']['utterances']} utterances.", "",
                  "| truth | heard | bridge said | correction | cause | status |", "|---|---|---|---|---|---|"]
        shown = 0
        for ex in v0["examples"]:
            harm = [c for c in ex["corrections"] if f" {c['from'].lower()} " in f" {ex['truth'].lower()} "]
            if not harm or shown >= 8:
                continue
            c = harm[0]
            cause = ("`slot`/`Salt` share key SRT, 2 edits apart; Salt is a fragment of the locality Salt Lake; confidence gate open"
                     if c["to"] == "Salt" else
                     "a token of three letters or fewer matched a lexicon name" if len(c["from"]) <= 3 else
                     "a dialogue frame word sits one key away from a lexicon form")
            lines.append(f"| {ex['truth']} | {ex['heard']} | {ex['corrected']} | {c['from']} → {c['to']} | {cause} | fixed (frame words, 4-letter minimum) |")
            shown += 1
        lines.append("")
    if v1:
        lines += ["## 2. Still wrong after the guards: what the bridge cannot repair", "",
                  "| truth | heard | bridge said | why not repaired | status |", "|---|---|---|---|---|"]
        shown = 0
        for ex in v1["examples"]:
            if ex["entity_errors_on"] == 0 or shown >= 8:
                continue
            heard = ex["heard"].lower()
            if len(heard.split()) < len(ex["truth"].split()) - 2 or any(w in heard for w in ("is there", "what is", "i want", "do you")):
                why = "the recogniser paraphrased or translated the sentence; the entity was dropped, not mangled"
            elif any(len(w) > 11 for w in heard.split()):
                why = "words merged into one token (e.g. 'Jadavpuvali'); n-gram matching cannot split a token"
            else:
                why = "corrupted beyond edit distance 2, or the corrupted form collided with no lexicon key"
            lines.append(f"| {ex['truth']} | {ex['heard']} | {ex['corrected']} | {why} | open (recogniser biasing is the lever) |")
            shown += 1
        lines.append("")
        lines += ["## 3. Absurd-but-harmless: `to do` → `thyroid profile`", "",
                  "The alias `t3 t4` keys to `TT` once digits are dropped, two edits from `to do`. Not harmful by the",
                  "metric (neither phrase was in the truth) but obviously wrong. Fixed: a lexicon form with fewer than",
                  "four letters is never evidence for a replacement. Test: `test_a_lexicon_form_with_too_few_letters_is_not_evidence`.", ""]
    if lt:
        lines += ["## 4. Outcomes under load: the calendar fills", "",
                  "| concurrent callers | expected outcome | what happened instead |", "|---|---|---|"]
        for r in lt["levels"]:
            mm = ", ".join(f"{k} ×{v}" for k, v in r.get("mismatches", {}).items()) or "—"
            lines.append(f"| {r['concurrency']} | {r['outcome_rate']:.0%} | {mm} |")
        lines += ["", "Sixty scripted callers ask for the same morning in one calendar; once it is full the agent offers",
                  "another time or takes a callback and the fixed script does not follow. BOOKED→LEAD_CAPTURED and",
                  "BOOKED→ABANDONED here are the calendar working. Status: documented, not a bug; the harness reports",
                  "the mismatch histogram next to the error count (always 0).", ""]
    lines += ["## 5. Things the synthetic harness could not see", "",
              "- Whisper's per-word probabilities were below the 0.85 gate for 80 % of words: the bridge's first",
              "  condition was effectively off. Lesson: calibrate the confidence threshold per recogniser.",
              "- Translation: decoded as English, Whisper rewrote Hinglish sentences as English questions.",
              "  Lesson: run the recogniser in a Hinglish mode (`hi-Latn` on Deepgram) and bias it with the lexicon.",
              "- The policy is scripted-caller-shaped: a real caller who is offered an alternative accepts it; the",
              "  load-test script does not. Lesson for the user study: measure with people (docs/study/protocol.md).", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
